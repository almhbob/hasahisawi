/** SVG كامل لأيقونة (للتصدير إلى فيجما أو الويب) */
export function glyphSvg(g: Glyph, color: string, size = 24, accent = GLYPH_GOLD) {
  const els = g.parts.map((p) => {
    const col = p.accent ? accent : color;
    const paint = p.fill ? `fill="${col}" stroke="none"` : `fill="none" stroke="${col}" stroke-width="${GLYPH_STROKE}" stroke-linecap="round" stroke-linejoin="round"`;
    return p.c ? `<circle cx="${p.c[0]}" cy="${p.c[1]}" r="${p.c[2]}" ${paint}/>` : `<path d="${p.d}" ${paint}/>`;
  }).join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24">${els}</svg>`;
}
